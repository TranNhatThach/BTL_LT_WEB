Create database QUANLYCHITIEUSINHVIEN;
GO
use [QUANLYCHITIEUSINHVIEN];
GO



CREATE TABLE SINHVIEN (
    MaSV       VARCHAR(20)    NOT NULL,
    HoTen      NVARCHAR(100)  NOT NULL,
    NgaySinh   DATE           NULL,
    GioiTinh   NVARCHAR(20)   NULL,
    Email      VARCHAR(255)   NULL,
    SDT        VARCHAR(20)    NULL,
    CONSTRAINT PK_SINHVIEN PRIMARY KEY (MaSV)
);

CREATE TABLE TAIKHOAN (
    MaTK          VARCHAR(20)    NOT NULL,
    MaSV          VARCHAR(20)    NOT NULL,
    TenDangNhap   VARCHAR(100)   NOT NULL,
    MatKhau       NVARCHAR(255)  NOT NULL,
    TrangThai     NVARCHAR(30)   NOT NULL DEFAULT N'Hoạt động',
    CONSTRAINT PK_TAIKHOAN PRIMARY KEY (MaTK),
    CONSTRAINT FK_TAIKHOAN_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT UQ_TAIKHOAN_MASV UNIQUE (MaSV),
    CONSTRAINT UQ_TAIKHOAN_TENDANGNHAP UNIQUE (TenDangNhap)
);

CREATE TABLE NGUONTHU (
    MaNguonThu  VARCHAR(20)    NOT NULL,
    TenNguon    NVARCHAR(100)  NOT NULL,
    MoTa        NVARCHAR(255)  NULL,
    CONSTRAINT PK_NGUONTHU PRIMARY KEY (MaNguonThu)
);

CREATE TABLE DANHMUC (
    MaDM      VARCHAR(20)    NOT NULL,
    TenDM     NVARCHAR(100)  NOT NULL,
    LoaiDM    NVARCHAR(30)   NOT NULL,
    MoTa      NVARCHAR(255)  NULL,
    CONSTRAINT PK_DANHMUC PRIMARY KEY (MaDM)
);

CREATE TABLE KHOANTHU (
    MaKT        VARCHAR(20)    NOT NULL,
    MaSV        VARCHAR(20)    NOT NULL,
    MaNguonThu  VARCHAR(20)    NOT NULL,
    NgayThu     DATE           NOT NULL,
    SoTien      DECIMAL(18,2)  NOT NULL,
    NoiDung     NVARCHAR(500)  NULL,
    CONSTRAINT PK_KHOANTHU PRIMARY KEY (MaKT),
    CONSTRAINT FK_KHOANTHU_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT FK_KHOANTHU_NGUONTHU FOREIGN KEY (MaNguonThu) REFERENCES NGUONTHU(MaNguonThu),
    CONSTRAINT CK_KHOANTHU_SOTIEN CHECK (SoTien > 0)
);

CREATE TABLE KHOANCHI (
    MaKC      VARCHAR(20)    NOT NULL,
    MaSV      VARCHAR(20)    NOT NULL,
    MaDM      VARCHAR(20)    NOT NULL,
    NgayChi   DATE           NOT NULL,
    SoTien    DECIMAL(18,2)  NOT NULL,
    NoiDung   NVARCHAR(500)  NULL,
    CONSTRAINT PK_KHOANCHI PRIMARY KEY (MaKC),
    CONSTRAINT FK_KHOANCHI_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT FK_KHOANCHI_DANHMUC FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM),
    CONSTRAINT CK_KHOANCHI_SOTIEN CHECK (SoTien > 0)
);

CREATE TABLE NGANSACH (
    MaNganSach  VARCHAR(20)    NOT NULL,
    MaSV        VARCHAR(20)    NOT NULL,
    MaDM        VARCHAR(20)    NOT NULL,
    Thang       TINYINT        NOT NULL,
    Nam         SMALLINT       NOT NULL,
    HanMuc      DECIMAL(18,2)  NOT NULL,
    CONSTRAINT PK_NGANSACH PRIMARY KEY (MaNganSach),
    CONSTRAINT FK_NGANSACH_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT FK_NGANSACH_DANHMUC FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM),
    CONSTRAINT UQ_NGANSACH_SV_DM_THANG_NAM UNIQUE (MaSV, MaDM, Thang, Nam),
    CONSTRAINT CK_NGANSACH_THANG CHECK (Thang BETWEEN 1 AND 12),
    CONSTRAINT CK_NGANSACH_HANMUC CHECK (HanMuc >= 0)
);

CREATE TABLE MUCTIEUTIETKIEM (
    MaMT             VARCHAR(20)    NOT NULL,
    MaSV             VARCHAR(20)    NOT NULL,
    TenMucTieu       NVARCHAR(150)  NOT NULL,
    SoTienMucTieu    DECIMAL(18,2)  NOT NULL,
    NgayBatDau       DATE           NOT NULL,
    NgayKetThuc      DATE           NOT NULL,
    TrangThai        NVARCHAR(30)   NOT NULL DEFAULT N'Đang thực hiện',
    CONSTRAINT PK_MUCTIEUTIETKIEM PRIMARY KEY (MaMT),
    CONSTRAINT FK_MUCTIEUTIETKIEM_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT CK_MUCTIEUTIETKIEM_SOTIEN CHECK (SoTienMucTieu > 0),
    CONSTRAINT CK_MUCTIEUTIETKIEM_NGAY CHECK (NgayKetThuc >= NgayBatDau)
);

CREATE TABLE TIETKIEM (
    MaTietKiem  VARCHAR(20)    NOT NULL,
    MaMT        VARCHAR(20)    NOT NULL,
    NgayTietKiem DATE          NOT NULL,
    SoTien      DECIMAL(18,2)  NOT NULL,
    NoiDung     NVARCHAR(500)  NULL,
    CONSTRAINT PK_TIETKIEM PRIMARY KEY (MaTietKiem),
    CONSTRAINT FK_TIETKIEM_MUCTIEUTIETKIEM FOREIGN KEY (MaMT) REFERENCES MUCTIEUTIETKIEM(MaMT),
    CONSTRAINT CK_TIETKIEM_SOTIEN CHECK (SoTien > 0)
);

CREATE TABLE THONGBAO (
    MaTB       VARCHAR(20)    NOT NULL,
    MaSV       VARCHAR(20)    NOT NULL,
    TieuDe     NVARCHAR(200)  NOT NULL,
    NoiDung    NVARCHAR(1000) NOT NULL,
    NgayTao    DATETIME2      NOT NULL DEFAULT SYSDATETIME(),
    LoaiTB     NVARCHAR(50)   NULL,
    TrangThai  NVARCHAR(30)   NOT NULL DEFAULT N'Chưa đọc',
    CONSTRAINT PK_THONGBAO PRIMARY KEY (MaTB),
    CONSTRAINT FK_THONGBAO_SINHVIEN FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV)
);

CREATE TABLE ANHKHOANCHI (
    MaAnh        VARCHAR(20)    NOT NULL,
    MaKC         VARCHAR(20)    NOT NULL,
    DuongDanAnh  NVARCHAR(500)  NOT NULL,
    NgayThem     DATETIME2      NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_ANHKHOANCHI PRIMARY KEY (MaAnh),
    CONSTRAINT FK_ANHKHOANCHI_KHOANCHI FOREIGN KEY (MaKC) REFERENCES KHOANCHI(MaKC)
);
